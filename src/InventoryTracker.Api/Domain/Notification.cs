namespace InventoryTracker.Api.Domain;

/// <summary>
/// A message to all Managers about something that needs attention (US-23). Table <c>Notifications</c>.
/// </summary>
/// <remarks>
/// A notification is created once and shared by every Manager. Whether a particular Manager has read it is a
/// <see cref="NotificationRead"/> row, so read status is per Manager (decision #7) and a Manager added later sees
/// every older notification as unread (AC-23.4). Notifications are added in the same write transaction as the
/// event that raises them (architecture 5.2) and are never deleted (AC-23.5).
/// </remarks>
public class Notification
{
    /// <summary>Primary key, generated by the database.</summary>
    public int Id { get; set; }

    /// <summary>Which of the five kinds this is. Stored as the enum name.</summary>
    public NotificationType Type { get; set; }

    /// <summary>Foreign key to the production order it is about. Every type relates to an order.</summary>
    public int ProductionOrderNumber { get; set; }

    /// <summary>The order, when loaded.</summary>
    public ProductionOrder ProductionOrder { get; set; } = null!;

    /// <summary>Foreign key to the complementary order (ComplementaryAwaitingApproval only).</summary>
    public int? ComplementaryOrderNumber { get; set; }

    /// <summary>The complementary order, when loaded.</summary>
    public ComplementaryOrder? ComplementaryOrder { get; set; }

    /// <summary>When the notification was raised (UTC). Lists are newest first (decision #17).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>The finished text from design 7.3, up to 1,000 characters.</summary>
    public string Message { get; set; } = string.Empty;

    /// <summary>The <c>data</c> object of design 5.10, stored as camelCase JSON text so its shape can differ per type.</summary>
    public string DataJson { get; set; } = string.Empty;

    /// <summary>One row per Manager who has read it.</summary>
    public List<NotificationRead> Reads { get; set; } = [];
}

using InventoryTracker.Api.Auth;

namespace InventoryTracker.Api.Domain;

/// <summary>
/// An instruction to move leftover raw material from production storage back to the Warehouse (US-22).
/// Table <c>Returns</c>.
/// </summary>
/// <remarks>
/// Two steps (decision #11): a Manager instructs it (Pending), then the Warehouse records receiving it, which
/// writes the ReturnedToWarehouse movement. While Pending, its quantity is excluded from free leftover (D-4).
/// It has its own number sequence, used as the primary key (design 2.1). Returns are never deleted.
/// </remarks>
public class LeftoverReturn
{
    /// <summary>The return number and primary key, generated by the database.</summary>
    public int Number { get; set; }

    /// <summary>Foreign key to the raw material being returned.</summary>
    public int ItemId { get; set; }

    /// <summary>The raw material, when loaded.</summary>
    public Item Item { get; set; } = null!;

    /// <summary>The quantity to return; greater than 0.</summary>
    public decimal Quantity { get; set; }

    /// <summary>Why the material is returned; required, up to 500 characters.</summary>
    public string Reason { get; set; } = string.Empty;

    /// <summary>Optional link to a production order, in any status.</summary>
    public int? ProductionOrderNumber { get; set; }

    /// <summary>The linked order, when loaded.</summary>
    public ProductionOrder? ProductionOrder { get; set; }

    /// <summary>Current status. Stored as the enum name.</summary>
    public ReturnStatus Status { get; set; }

    /// <summary>AC-05.3: when the Manager instructed the return (UTC).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>AC-05.3: foreign key to the Manager who instructed the return.</summary>
    public string CreatedById { get; set; } = string.Empty;

    /// <summary>The Manager who instructed the return, when loaded.</summary>
    public AppUser CreatedBy { get; set; } = null!;

    /// <summary>AC-05.3: when the Warehouse recorded receiving it.</summary>
    public DateTime? ReceivedAt { get; set; }

    /// <summary>AC-05.3: foreign key to the user who recorded receiving it.</summary>
    public string? ReceivedById { get; set; }

    /// <summary>That user, when loaded.</summary>
    public AppUser? ReceivedBy { get; set; }

    /// <summary>AC-05.3: when a Manager cancelled it.</summary>
    public DateTime? CancelledAt { get; set; }

    /// <summary>AC-05.3: foreign key to the Manager who cancelled it.</summary>
    public string? CancelledById { get; set; }

    /// <summary>That Manager, when loaded.</summary>
    public AppUser? CancelledBy { get; set; }
}

using InventoryTracker.Api.Auth;

namespace InventoryTracker.Api.Domain;

/// <summary>
/// (v1.1) A business the company sells to (US-29). Sales orders pick their customer from this list. Table
/// <c>Customers</c>.
/// </summary>
/// <remarks>
/// <para>
/// Names follow the unit and item rule (architecture 3.1): <see cref="Name"/> as entered, in NFC, trimmed (decision
/// #170, <c>NameRules</c>), and <see cref="NameNormalized"/> with a unique index, so "Deli Norte" and "DELI NORTE"
/// are the same name, and so are two spellings of "Café" in different Unicode forms (AC-29.2).
/// </para>
/// <para>
/// <b>Why the id is never reused (AC-29.5, decision #162).</b> A customer can be deleted while no sales order names it.
/// The key is an SQLite <c>AUTOINCREMENT</c> key: an id, once committed, is never handed out again, even after the
/// customer is deleted, so an old link or bookmark with that id keeps answering <c>404</c> instead of quietly showing
/// somebody else. A rolled-back insert's id goes to the next customer; that is harmless, because an id is only returned
/// after the commit.
/// </para>
/// <para>
/// Every sales order's foreign key to its customer is <c>Restrict</c>, so the database itself refuses to delete a
/// customer that a sales order names, even if a delete and a new sales order race (AC-29.8).
/// </para>
/// </remarks>
public class Customer
{
    /// <summary>Primary key, generated by the database; once committed, never handed out again (AUTOINCREMENT, decision #162).</summary>
    public int Id { get; set; }

    /// <summary>
    /// AC-29.1: the name as entered, in NFC, trimmed (decision #170, <c>NameRules</c>), 1 to 100 characters. Shown
    /// everywhere as the current name (AC-29.3).
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// AC-29.2: <see cref="Name"/> normalized by <see cref="NameNormalizer"/> (NFC, trimmed, upper-cased; decision
    /// #170); unique across all customers. It is also
    /// the sort key of the reports, compared ordinally (architecture 3.1).
    /// </summary>
    public string NameNormalized { get; set; } = string.Empty;

    /// <summary>
    /// AC-29.1: optional notes, up to 500 characters; blank is stored as null (design 2.6). They may hold contact
    /// details, so they are never written to the log (decision #163).
    /// </summary>
    public string? Notes { get; set; }

    /// <summary>AC-29.4: a deactivated customer stays listed but cannot be chosen for a new sales order.</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>AC-29.1, AC-05.3: when the customer was created (UTC). The list is ordered by it, newest first (AC-29.6).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>AC-05.3: foreign key to the user who created the customer.</summary>
    public string CreatedById { get; set; } = string.Empty;

    /// <summary>The creator, when loaded.</summary>
    public AppUser CreatedBy { get; set; } = null!;
}

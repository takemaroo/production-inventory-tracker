using InventoryTracker.Api.Auth;

namespace InventoryTracker.Api.Domain;

/// <summary>
/// (v1.1) A customer's order for items, shipped from the Warehouse in one go (D-10, US-24 to US-27). Table
/// <c>SalesOrders</c>.
/// </summary>
/// <remarks>
/// <para>
/// <b>Its own number sequence (D-10).</b> The sales order number ("sales order #3") is the primary key and starts at 1,
/// separately from production orders, complementary orders and returns, because each table has its own key. So the
/// first sales order is #1 however many production orders exist, and messages call it "sales order #N" so it cannot be
/// confused with production "order #N".
/// </para>
/// <para>
/// <b>Never reused (decision #162).</b> AUTOINCREMENT: a number, once committed, is never handed out again, even if
/// that row were deleted. A rolled-back insert's number goes to the next sales order; that is harmless, because a number
/// is only returned and logged after the commit (decision #163). Sales orders are never deleted (PRD section 5).
/// </para>
/// <para>
/// AC-05.3: each status the sales order reaches is recorded as a time and a user. The status history in responses
/// (design 5.12) is built from these three pairs; there is no history table, because each status is reached at most
/// once.
/// </para>
/// </remarks>
public class SalesOrder
{
    /// <summary>The sales order number and primary key, generated by the database from 1 (D-10).</summary>
    public int Number { get; set; }

    /// <summary>
    /// AC-24.1: foreign key to the customer. <c>Restrict</c>, so a customer that a sales order names cannot be deleted
    /// (AC-29.5, AC-29.8).
    /// </summary>
    public int CustomerId { get; set; }

    /// <summary>The customer, when loaded.</summary>
    public Customer Customer { get; set; } = null!;

    /// <summary>AC-24.1: the customer's own reference (for example their purchase order number), up to 100 characters; blank is stored as null.</summary>
    public string? CustomerReference { get; set; }

    /// <summary>Current status. Stored as the enum name.</summary>
    public SalesOrderStatus Status { get; set; }

    /// <summary>AC-24.1, AC-05.3: when the sales order was created (UTC). Lists are ordered by it, newest first.</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>AC-05.3: foreign key to the user who created the sales order.</summary>
    public string CreatedById { get; set; } = string.Empty;

    /// <summary>The creator, when loaded.</summary>
    public AppUser CreatedBy { get; set; } = null!;

    /// <summary>
    /// AC-26.1: when the sales order was shipped. This is the shipment time of D-13, which the reports filter on, and
    /// equals the <c>OccurredAt</c> of every movement the shipment wrote (architecture 5.3).
    /// </summary>
    public DateTime? ShippedAt { get; set; }

    /// <summary>AC-26.1, AC-05.3: foreign key to the user who shipped it.</summary>
    public string? ShippedById { get; set; }

    /// <summary>The user who shipped it, when loaded.</summary>
    public AppUser? ShippedBy { get; set; }

    /// <summary>AC-26.1, AC-26.8: the optional note entered at shipment, up to 500 characters; blank is stored as null.</summary>
    public string? ShipmentNote { get; set; }

    /// <summary>AC-27.1, AC-05.3: when the sales order was cancelled.</summary>
    public DateTime? CancelledAt { get; set; }

    /// <summary>AC-27.1, AC-05.3: foreign key to the user who cancelled it.</summary>
    public string? CancelledById { get; set; }

    /// <summary>The user who cancelled it, when loaded.</summary>
    public AppUser? CancelledBy { get; set; }

    /// <summary>AC-27.1: the reason entered at cancellation, up to 500 characters; required when cancelled.</summary>
    public string? CancellationReason { get; set; }

    /// <summary>The latest of the three status times; shown in the list (design 5.12). Kept as a column so lists need no calculation.</summary>
    public DateTime StatusChangedAt { get; set; }

    /// <summary>AC-24.1: one line per item, 1 to 500 lines, in the order they were entered.</summary>
    public List<SalesOrderLine> Lines { get; set; } = [];
}

namespace InventoryTracker.Api.Domain;

/// <summary>
/// Something the business stocks: a raw material it buys or a finished product it makes (US-07). Table <c>Items</c>.
/// </summary>
/// <remarks>
/// An item can be deleted only while it is not "in use" (AC-07.3, AC-07.4): no movement, recipe line, order line,
/// production order, complementary-order line, return or (v1.1) sales order line refers to it (AC-28.5). The foreign
/// keys from those tables use <c>Restrict</c>, so the database also refuses to delete an item that is still referenced.
/// </remarks>
public class Item
{
    /// <summary>Primary key, generated by the database.</summary>
    public int Id { get; set; }

    /// <summary>The name as entered, trimmed, 1 to 100 characters (design 2.6).</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>AC-07.1: <see cref="Name"/> normalized by <see cref="NameNormalizer"/>; unique across all items.</summary>
    public string NameNormalized { get; set; } = string.Empty;

    /// <summary>Optional description, up to 500 characters (design 2.6).</summary>
    public string? Description { get; set; }

    /// <summary>Raw material or finished product (AC-07.1). Stored as the enum name.</summary>
    public ItemType Type { get; set; }

    /// <summary>Foreign key to the unit the item is measured in. AC-06.4: a unit in use cannot be deleted.</summary>
    public int UnitId { get; set; }

    /// <summary>
    /// The unit, when loaded. A <em>navigation property</em> lets code follow the foreign key as an object
    /// (<c>item.Unit.Name</c>). EF Core fills it only when the query asks for it with <c>Include</c> or a projection;
    /// otherwise it is null, which is why <c>null!</c> is used to silence the compiler here.
    /// </summary>
    public UnitOfMeasure Unit { get; set; } = null!;

    /// <summary>When the item was created (UTC). Lists are ordered by it, newest first (PRD 4.1).</summary>
    public DateTime CreatedAt { get; set; }
}

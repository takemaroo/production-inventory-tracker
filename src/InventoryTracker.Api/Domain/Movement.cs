using InventoryTracker.Api.Auth;

namespace InventoryTracker.Api.Domain;

/// <summary>
/// One change to the stock of one item (D-2). Table <c>Movements</c>.
/// </summary>
/// <remarks>
/// <para>
/// Stock is never stored as a balance. The stock of an item in a location is the sum of that column over the
/// item's movements (D-2, decision #20), so history and stock can never disagree (AC-11.4).
/// </para>
/// <para>
/// A movement has one signed change per location. Which columns each type fills (architecture 3.2):
/// Received W+; SentToProduction W−, P+; ConsumedInProduction P−; ProducedOutput W+; ReturnedToWarehouse W+, P−;
/// Adjustment exactly one of W or P; (v1.1) ShippedToCustomer W− only. A location the movement does not touch is null.
/// No movement is created with a zero quantity (PRD section 6 row 17).
/// </para>
/// <para>
/// AC-11.3: movements are insert-only. Every property is <c>init</c>, so code can set it only while creating the
/// object, and <c>AppDbContext</c> refuses to save a changed or deleted movement. Movements are always added
/// through <c>Features/Stock/StockLedger</c> (T-008), which also checks that no location goes below zero.
/// </para>
/// </remarks>
public class Movement
{
    /// <summary>Primary key, generated by the database.</summary>
    public int Id { get; init; }

    /// <summary>D-2: what kind of change this is. Stored as the enum name.</summary>
    public MovementType Type { get; init; }

    /// <summary>Foreign key to the item whose stock changed.</summary>
    public int ItemId { get; init; }

    /// <summary>The item, when loaded.</summary>
    public Item Item { get; init; } = null!;

    /// <summary>Signed change to the Warehouse stock; null when the Warehouse is not touched.</summary>
    public decimal? WarehouseChange { get; init; }

    /// <summary>Signed change to the Production storage stock; null when Production storage is not touched.</summary>
    public decimal? ProductionStorageChange { get; init; }

    /// <summary>AC-05.3: when the movement happened (UTC, whole seconds).</summary>
    public DateTime OccurredAt { get; init; }

    /// <summary>AC-05.3: foreign key to the user who performed the movement.</summary>
    public string UserId { get; init; } = string.Empty;

    /// <summary>The user, when loaded.</summary>
    public AppUser User { get; init; } = null!;

    /// <summary>
    /// The production order this movement belongs to, if any. Also set on a complementary send, to the parent
    /// order (design 5.6), so filtering by order number finds the complementary sends too.
    /// </summary>
    public int? ProductionOrderNumber { get; init; }

    /// <summary>The production order, when loaded.</summary>
    public ProductionOrder? ProductionOrder { get; init; }

    /// <summary>The complementary order this send belongs to (SentToProduction only).</summary>
    public int? ComplementaryOrderNumber { get; init; }

    /// <summary>The complementary order, when loaded.</summary>
    public ComplementaryOrder? ComplementaryOrder { get; init; }

    /// <summary>The leftover return this movement completes (ReturnedToWarehouse only, AC-22.4).</summary>
    public int? ReturnNumber { get; init; }

    /// <summary>The return, when loaded.</summary>
    public LeftoverReturn? Return { get; init; }

    /// <summary>The date on the delivery (Received only, US-09). A date without a time of day.</summary>
    public DateOnly? ReceiptDate { get; init; }

    /// <summary>Optional receipt note, up to 500 characters (Received only).</summary>
    public string? Note { get; init; }

    /// <summary>The reason for an adjustment or write-off, up to 500 characters (Adjustment only, US-12).</summary>
    public string? Reason { get; init; }

    /// <summary>
    /// (v1.1) AC-28.1: the sales order a shipment belongs to. Required on a shipment and allowed on no other movement
    /// (decision #157; the ledger enforces that from T-026). A <c>Restrict</c> foreign key, so it can only name a sales
    /// order that exists. A unique index on (sales order, item) lets the database refuse a second shipment movement for
    /// the same line (AC-26.10).
    /// </summary>
    public int? SalesOrderNumber { get; init; }

    /// <summary>The sales order, when loaded.</summary>
    public SalesOrder? SalesOrder { get; init; }
}

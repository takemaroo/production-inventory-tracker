namespace InventoryTracker.Api.Domain;

/// <summary>
/// (v1.1) One item and quantity on a sales order (AC-24.1). Table <c>SalesOrderLines</c>.
/// </summary>
/// <remarks>
/// <para>
/// An item appears at most once per sales order (AC-24.3); a unique index on (sales order, item) makes the database
/// refuse a second line for it. Because of that rule, "one shipment movement per (sales order, item)" is the same as
/// "one per line" (architecture 3.2, Movement).
/// </para>
/// <para>
/// <b>Why the unit is not copied onto the line.</b> An item on any sales order line, whatever the status, is "in use"
/// (AC-28.5), so its unit can never change afterwards; the line always shows the item's own unit.
/// </para>
/// <para>
/// The foreign keys are <c>Restrict</c>, not <c>Cascade</c>: sales orders are never deleted (PRD section 5), so their
/// lines are not either, and an item on a line cannot be deleted.
/// </para>
/// </remarks>
public class SalesOrderLine
{
    /// <summary>Primary key, generated by the database.</summary>
    public int Id { get; set; }

    /// <summary>Foreign key to the sales order.</summary>
    public int SalesOrderNumber { get; set; }

    /// <summary>The sales order, when loaded.</summary>
    public SalesOrder SalesOrder { get; set; } = null!;

    /// <summary>Position in the request body, from 1 (decision #162). "Line order" in responses and messages (AC-24.1, AC-26.3).</summary>
    public int LineNo { get; set; }

    /// <summary>Foreign key to the item: a raw material or a finished product (decision #144). Makes the item "in use" (AC-28.5).</summary>
    public int ItemId { get; set; }

    /// <summary>The item, when loaded.</summary>
    public Item Item { get; set; } = null!;

    /// <summary>AC-24.3: the quantity in the item's unit; greater than 0, at most 3 decimal places and 999,999,999.999.</summary>
    public decimal Quantity { get; set; }
}

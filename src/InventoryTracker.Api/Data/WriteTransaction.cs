using Microsoft.EntityFrameworkCore;

namespace InventoryTracker.Api.Data;

/// <summary>
/// The single way to change data: <c>db.InWriteTransactionAsync(...)</c> (architecture 5.2, decision #21).
/// </summary>
/// <remarks>
/// <para>
/// A database <em>transaction</em> groups several statements so they take effect together or not at all.
/// Until it is committed, nothing it wrote is visible to other connections; if it is rolled back (or simply
/// never committed), everything it wrote disappears.
/// </para>
/// <para>
/// PRD section 5 requires that every request that changes data "either completes fully or saves nothing", and that
/// two conflicting requests never both succeed. So every service that changes data does all its reads, checks and
/// writes inside the <c>work</c> passed to this method:
/// </para>
/// <code>
/// return await db.InWriteTransactionAsync(async () =>
/// {
///     // ... load records (404), validate (400), check state and stock (409) ...
///     var order = new ProductionOrder { /* ... */ };
///     db.ProductionOrders.Add(order);
///
///     // The order number is generated by the database, so it is still 0 here. Save first, still inside
///     // the transaction, so the response can show it. Nothing is permanent until the commit.
///     await db.SaveChangesAsync(cancellationToken);
///     return ToResponse(order);
/// }, cancellationToken);
/// </code>
/// <para>
/// Work that only changes existing rows (for example a status change) need not call <c>SaveChangesAsync</c>:
/// this method saves whatever is still pending before it commits.
/// </para>
/// <para>
/// Why this serializes writers on SQLite: EF Core's <c>BeginTransactionAsync</c> issues <c>BEGIN IMMEDIATE</c>,
/// which takes SQLite's single write lock at the start of the transaction, not at the first write. A second
/// request that calls this method waits (up to the connection's 30-second busy timeout) until the first commits,
/// and then reads the committed data. Two requests can therefore never both see the old stock or the old status.
/// WAL mode (set in <see cref="DatabaseSetup"/>) lets read-only requests carry on meanwhile.
/// </para>
/// <para>
/// PostgreSQL later: change only this class. After beginning the transaction, run
/// <c>SELECT pg_advisory_xact_lock(1)</c> to get the same one-writer-at-a-time behaviour.
/// </para>
/// </remarks>
public static class WriteTransaction
{
    /// <summary>
    /// Begins a write transaction, runs <paramref name="work"/>, saves the tracked changes and commits.
    /// If anything throws, nothing is saved and the exception is passed on unchanged.
    /// Database-generated keys are filled in only by <c>SaveChangesAsync</c>. Work that creates a row and returns
    /// its number should call <c>await db.SaveChangesAsync()</c> itself before building the response; this is safe
    /// because it is still inside the transaction.
    /// </summary>
    /// <typeparam name="T">What the work returns, usually the response body.</typeparam>
    /// <param name="db">The request's DbContext.</param>
    /// <param name="work">
    /// All the reads, checks and changes for one request. It may call <c>SaveChangesAsync</c> (needed to read
    /// generated keys); anything still unsaved when it returns is saved before the commit.
    /// </param>
    /// <param name="cancellationToken">Cancels the save and commit, for example when the client disconnects.</param>
    /// <exception cref="InvalidOperationException">A transaction is already open on <paramref name="db"/>.</exception>
    public static async Task<T> InWriteTransactionAsync<T>(
        this AppDbContext db, Func<Task<T>> work, CancellationToken cancellationToken = default)
    {
        // One transaction per request. A nested call would be a design mistake (the inner "commit" would not
        // really commit), so it fails loudly instead of half-working.
        if (db.Database.CurrentTransaction is not null)
        {
            throw new InvalidOperationException("A write transaction is already open on this DbContext; call InWriteTransactionAsync once per request.");
        }

        // `await using` disposes the transaction when this block ends. Disposing a transaction that was not
        // committed rolls it back, so every exit path except the successful one below saves nothing.
        await using var transaction = await db.Database.BeginTransactionAsync(cancellationToken);
        try
        {
            var result = await work();

            // SaveChangesAsync sends the INSERT/UPDATE statements inside the open transaction;
            // CommitAsync makes them permanent and visible to other connections, and releases the write lock.
            await db.SaveChangesAsync(cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            return result;
        }
        catch
        {
            // The rows are rolled back, but the DbContext still tracks the objects the work added or changed.
            // Forget them too, so a later SaveChanges on this context cannot save them by accident.
            db.ChangeTracker.Clear();
            throw;
        }
    }

    /// <summary>
    /// The same as <see cref="InWriteTransactionAsync{T}"/> for work that returns nothing (for example a delete).
    /// </summary>
    /// <param name="db">The request's DbContext.</param>
    /// <param name="work">All the reads, checks and changes for one request.</param>
    /// <param name="cancellationToken">Cancels the save and commit.</param>
    public static Task InWriteTransactionAsync(
        this AppDbContext db, Func<Task> work, CancellationToken cancellationToken = default) =>
        db.InWriteTransactionAsync(
            async () =>
            {
                await work();
                return true;
            },
            cancellationToken);
}

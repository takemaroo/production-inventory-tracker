using InventoryTracker.Api.Common.Errors;
using InventoryTracker.Api.Common.Paging;
using InventoryTracker.Api.Common.Validation;
using InventoryTracker.Api.Data;
using InventoryTracker.Api.Data.Configurations;
using InventoryTracker.Api.Domain;
using Microsoft.EntityFrameworkCore;

namespace InventoryTracker.Api.Features.Units;

/// <summary>
/// Every rule for units of measure (US-06): list, read, create, rename and delete.
/// </summary>
/// <remarks>
/// <para>
/// This is the middle layer of the controller → service → DbContext flow that every feature follows
/// (architecture 2). <see cref="UnitsController"/> only maps HTTP to C# calls; this class holds the rules; the
/// <see cref="AppDbContext"/> it receives through its constructor turns LINQ queries into SQL. The service is
/// created once per request (see <c>FeatureRegistration</c>), so it shares that request's DbContext.
/// </para>
/// <para>
/// A broken rule is never returned as a value: the service throws an <see cref="ApiException"/> subclass and the
/// central handler writes the design 6 error body. Every change runs inside
/// <see cref="WriteTransaction.InWriteTransactionAsync{T}"/>, so a refused request saves nothing (PRD 4.1, "rejected").
/// Checks run in the design 2.2 order: <c>404</c> for the id in the URL, then <c>400</c> input, then <c>409</c> state.
/// </para>
/// </remarks>
public sealed class UnitService(AppDbContext db)
{
    /// <summary>AC-06.4: the exact PRD message for deleting a unit an item still uses.</summary>
    public const string UnitInUseMessage = "Unit is used by one or more items.";

    /// <summary>Design 7.2: the code for a duplicate unit name (AC-06.2).</summary>
    public const string UnitNameTakenCode = "unit-name-taken";

    /// <summary>Design 7.2: the code for deleting a unit in use (AC-06.4).</summary>
    public const string UnitInUseCode = "unit-in-use";

    /// <summary>
    /// AC-06.1: one page of units, newest first (PRD 4.1).
    /// </summary>
    /// <remarks>
    /// Units have no creation time (architecture 3.2), so "newest first" is by id, highest first. The key is an
    /// <c>AUTOINCREMENT</c> column, so SQLite gives each new row a higher id than any row it ever stored, even one
    /// since deleted; a higher id therefore always means created later.
    /// </remarks>
    public async Task<PagedResult<UnitResponse>> ListAsync(PageQuery page, CancellationToken cancellationToken)
    {
        page.ThrowIfInvalid();

        // No AsNoTracking here: a query that ends in Select(...) to a response record returns plain objects, not
        // entities, so EF Core has nothing to track. AsNoTracking matters only when whole entities are loaded and
        // will not be changed.
        return await db.Units
            .OrderByDescending(unit => unit.Id)
            .Select(unit => new UnitResponse(unit.Id, unit.Name))
            .ToPagedResultAsync(page, cancellationToken);
    }

    /// <summary>Returns one unit, or <c>404</c> "Unit {id} not found.".</summary>
    public async Task<UnitResponse> GetAsync(int id, CancellationToken cancellationToken)
    {
        var unit = await db.Units
            .Where(candidate => candidate.Id == id)
            .Select(candidate => new UnitResponse(candidate.Id, candidate.Name))
            .SingleOrDefaultAsync(cancellationToken);

        return unit ?? throw NotFound(id);
    }

    /// <summary>
    /// AC-06.1, AC-06.2: creates a unit with a trimmed name of 1 to 50 characters that no other unit has, ignoring
    /// letter case.
    /// </summary>
    public Task<UnitResponse> CreateAsync(UnitRequest request, CancellationToken cancellationToken) =>
        db.InWriteTransactionAsync(async () =>
        {
            var name = ValidName(request);
            await ThrowIfNameTakenAsync(name, exceptId: null, cancellationToken);

            var unit = new UnitOfMeasure { Name = name, NameNormalized = NameNormalizer.Normalize(name) };
            db.Units.Add(unit);

            // The id is generated by the database, so it is still 0 until the row is saved. Saving here, inside the
            // transaction, lets the 201 response (and its Location header) carry the real id.
            await db.SaveChangesAsync(cancellationToken);
            return ToResponse(unit);
        }, cancellationToken);

    /// <summary>AC-06.3: renames a unit, under the same rules as creating one.</summary>
    public Task<UnitResponse> UpdateAsync(int id, UnitRequest request, CancellationToken cancellationToken) =>
        db.InWriteTransactionAsync(async () =>
        {
            // Design 2.2 step 3 before step 4: an unknown id is 404 even when the name is also invalid.
            // FindAsync looks the row up by primary key and keeps it tracked, so changes to it are saved later.
            var unit = await db.Units.FindAsync([id], cancellationToken) ?? throw NotFound(id);

            var name = ValidName(request);

            // The unit's own current name does not count as taken, so "kg" can be renamed to "KG".
            await ThrowIfNameTakenAsync(name, exceptId: id, cancellationToken);

            // The unit was loaded with tracking, so EF Core notices these changes and InWriteTransactionAsync saves them.
            unit.Name = name;
            unit.NameNormalized = NameNormalizer.Normalize(name);
            return ToResponse(unit);
        }, cancellationToken);

    /// <summary>AC-06.4: deletes a unit that no item uses; otherwise <c>409</c> "Unit is used by one or more items.".</summary>
    public Task DeleteAsync(int id, CancellationToken cancellationToken) =>
        db.InWriteTransactionAsync(async () =>
        {
            var unit = await db.Units.FindAsync([id], cancellationToken) ?? throw NotFound(id);

            // AC-06.4. The check and the delete are in one write transaction, so no item can be given this unit in
            // between. The Restrict foreign key from Items is the database's own backstop, but only a last one: a
            // FOREIGN KEY failure means this check is wrong, so it is answered as 500 internal-error, not 409
            // (decision #46). This check is what gives the client the readable 409. Items are the only table that
            // refers to units; UnitsTests.Unit_in_use_check_covers_every_foreign_key_to_units fails if another is added.
            if (await db.Items.AnyAsync(item => item.UnitId == id, cancellationToken))
            {
                throw new ConflictException(UnitInUseCode, UnitInUseMessage);
            }

            db.Units.Remove(unit);
        }, cancellationToken);

    /// <summary>
    /// AC-06.1, AC-06.2, design 2.6: the trimmed name, or a <c>400</c> when it is missing, blank or longer than 50.
    /// </summary>
    private static string ValidName(UnitRequest request)
    {
        var name = Text.Clean(request.Name);
        var errors = new ValidationErrors();
        if (name is null)
        {
            errors.Add("name", "Name is required.");
        }
        // Decision #116: counted in Unicode code points, so an emoji is one character (Text.Length).
        else if (Text.Length(name) > ColumnRules.UnitNameLength)
        {
            errors.Add("name", $"Name must be {ColumnRules.UnitNameLength} characters or fewer.");
        }

        errors.ThrowIfAny();
        return name!;
    }

    /// <summary>
    /// AC-06.2: <c>409</c> when another unit already has this name, ignoring letter case.
    /// </summary>
    /// <remarks>
    /// The comparison is on <c>NameNormalized</c>, the same column the unique index covers (decision #30). Two
    /// simultaneous creates cannot both pass this check, because write transactions run one at a time
    /// (architecture 5.2); the index would still refuse the second with <c>409</c> <c>concurrent-change</c>.
    /// </remarks>
    private async Task ThrowIfNameTakenAsync(string name, int? exceptId, CancellationToken cancellationToken)
    {
        var normalized = NameNormalizer.Normalize(name);
        var taken = await db.Units.AnyAsync(
            unit => unit.NameNormalized == normalized && unit.Id != exceptId, cancellationToken);

        if (taken)
        {
            throw new ConflictException(UnitNameTakenCode, $"A unit named '{name}' already exists.");
        }
    }

    private static NotFoundException NotFound(int id) => new($"Unit {id} not found.");

    private static UnitResponse ToResponse(UnitOfMeasure unit) => new(unit.Id, unit.Name);
}

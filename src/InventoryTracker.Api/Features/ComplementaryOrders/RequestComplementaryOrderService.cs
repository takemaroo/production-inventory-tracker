using InventoryTracker.Api.Common.Errors;
using InventoryTracker.Api.Common.Time;
using InventoryTracker.Api.Common.Validation;
using InventoryTracker.Api.Data;
using InventoryTracker.Api.Data.Configurations;
using InventoryTracker.Api.Domain;
using InventoryTracker.Api.Features.Notifications;
using InventoryTracker.Api.Features.ProductionOrders;
using Microsoft.EntityFrameworkCore;

namespace InventoryTracker.Api.Features.ComplementaryOrders;

/// <summary>
/// Requesting a complementary order (US-16): a production user asks for more of some materials for the order that is
/// running, with a reason, so the line does not stop and the extra use is on record.
/// </summary>
/// <remarks>
/// <para>
/// <b>What a request does, in plain words.</b> It writes a record, never stock. The new complementary order gets its own
/// number, status PendingApproval, a link to its parent order, and who asked and when (AC-16.1). Every Manager is told
/// through one ComplementaryAwaitingApproval notification (AC-23.2), because a Manager must approve it before any
/// material leaves the warehouse (decision #4, US-17). Material moves only when an approved request is sent (T-018).
/// </para>
/// <para>
/// <b>Why only while the parent is InProduction</b> (AC-16.2, PRD section 6 row 6). A complementary order tops up the
/// run that is going on: before the send there is no run yet (the order's own send covers its plan), and after
/// completion or cancellation the run is over. Its materials must already be on the parent order (AC-16.3), because the
/// extra is added to that order line's complementary sends and counted in its usage (D-3, D-9). A parent can have several
/// complementary orders (AC-16.4), each decided and sent on its own.
/// </para>
/// <para>
/// <b>Everything in one write transaction</b> (architecture 5.2). The parent's status is checked and the complementary
/// order and its notification are added inside one <see cref="WriteTransaction.InWriteTransactionAsync{T}"/> call, which
/// on SQLite holds the database's single write lock from the first read to the commit. So:
/// </para>
/// <list type="bullet">
/// <item>A request and the parent's completion or cancellation never interleave. If the request is first, the completion
/// or cancellation that follows finds the new PendingApproval request and cancels it automatically (AC-19.6, AC-21.4). If
/// the request is second, it finds the order Completed or Cancelled and gets <c>409</c> <c>parent-not-in-production</c>.
/// Either way no open request is left behind for an order that has ended.</item>
/// <item>Simultaneous requests get different, consecutive numbers: the number is generated by the database while the
/// lock is held (design 2.1).</item>
/// <item>The request and its notification are committed together or not at all ("Notifications match events").</item>
/// </list>
/// <para>
/// <b>Check order</b> (design 2.2, architecture 5.1): the parent order in the URL (<c>404</c>), the body (<c>400</c>
/// <c>validation</c>), then the parent's state (<c>409</c>). There are no ranges or stock to check, since nothing moves.
/// </para>
/// </remarks>
public sealed class RequestComplementaryOrderService(
    AppDbContext db,
    ComplementaryOrderService complementaryOrders,
    Clock clock,
    ILogger<RequestComplementaryOrderService> logger)
{
    /// <summary>Design 7.2: the code for a request on an order that is not InProduction (AC-16.2).</summary>
    public const string ParentNotInProductionCode = "parent-not-in-production";

    /// <summary>
    /// AC-16.1: raises a complementary order for InProduction order <paramref name="orderNumber"/>: its own number, status
    /// PendingApproval, the reason and the requested lines, who and when; and one ComplementaryAwaitingApproval
    /// notification (AC-23.2). Moves no stock. Returns the new complementary order (design 5.8).
    /// </summary>
    /// <param name="orderNumber">The parent order number from the URL.</param>
    /// <param name="request">The body: reason and lines.</param>
    /// <param name="userId">The signed-in Production or Manager user, from the token's <c>sub</c> claim (AC-05.3).</param>
    /// <param name="cancellationToken">Fires when the client disconnects.</param>
    /// <exception cref="NotFoundException"><c>404</c>: no order has this number.</exception>
    /// <exception cref="ValidationException">
    /// <c>400</c> <c>validation</c>: a bad reason or bad lines (AC-16.3); or <c>too-many-lines</c> for more than
    /// <see cref="RequestLimits.MaxLines"/> lines (SEC-01, checked before the <c>404</c>).
    /// </exception>
    /// <exception cref="ConflictException"><c>409</c> <c>parent-not-in-production</c> (AC-16.2).</exception>
    public async Task<ComplementaryOrderResponse> RequestAsync(
        int orderNumber, ComplementaryOrderRequest request, string userId, CancellationToken cancellationToken)
    {
        // SEC-01: refused before the write transaction; why, and what stays inside: RequestLimits.CheckLineCount.
        RequestLimits.CheckLineCount(request.Lines);

        var response = await db.InWriteTransactionAsync(async () =>
        {
            // Design 2.2 step 3: the parent order named in the URL, with its lines' materials and units, for the
            // matching, the messages and the notification. Only read, never changed, so not tracked.
            var parent = await db.ProductionOrders
                .AsNoTracking()
                .Include(order => order.Lines).ThenInclude(line => line.RawMaterial).ThenInclude(item => item.Unit)
                .SingleOrDefaultAsync(order => order.Number == orderNumber, cancellationToken)
                ?? throw new NotFoundException($"Order #{orderNumber} not found.");

            // Step 4: the body (AC-16.3). Step 5: the parent's state (AC-16.2).
            var (reason, lines) = await ValidateAsync(parent, request, cancellationToken);
            CheckParentInProduction(parent);

            var now = clock.UtcNow;
            var complementary = new ComplementaryOrder
            {
                // AC-16.1: the link to the parent, PendingApproval, and who asked and when (AC-05.3).
                ParentOrderNumber = parent.Number,
                Status = ComplementaryOrderStatus.PendingApproval,
                Reason = reason,
                RequestedAt = now,
                RequestedById = userId,

                // Lines keep the order the client listed them in (ComplementaryOrderLine.LineNo, "Position, as submitted").
                Lines = lines
                    .Select((line, position) => new ComplementaryOrderLine
                    {
                        LineNo = position + 1,
                        RawMaterialId = line.Line.RawMaterialId,
                        RequestedAmount = line.Quantity,
                    })
                    .ToList(),
            };
            db.ComplementaryOrders.Add(complementary);

            // The number is generated by the database, so save first (still inside the transaction): the
            // notification below names it. Design 2.1: its own sequence, separate from the production orders'.
            await db.SaveChangesAsync(cancellationToken);

            await AddNotificationAsync(parent, complementary.Number, lines, reason, userId, now, cancellationToken);
            await db.SaveChangesAsync(cancellationToken);

            return await complementaryOrders.ReadAsync(complementary.Number, cancellationToken);
        }, cancellationToken);

        // Architecture 6, Logging: each state change, with the numbers and the user, only after the commit, so the log
        // never reports a request that was rolled back.
        logger.LogInformation(
            "Complementary order {ComplementaryOrderNumber} requested for order {OrderNumber} by user {UserId}.",
            response.Number, orderNumber, userId);
        return response;
    }

    /// <summary>
    /// Design 2.2 step 4 for a request body (AC-16.3). Every problem is reported in one <c>400</c> <c>validation</c>,
    /// keyed by the field's JSON path:
    /// </summary>
    /// <remarks>
    /// <list type="bullet">
    /// <item><c>reason</c>: required, 1 to 500 characters after trimming (design 2.6): "Reason is required." or "Reason
    /// must be 500 characters or fewer.".</item>
    /// <item><c>lines</c>: at least one ("At least one line is required.", for a missing, <c>null</c> or empty list).</item>
    /// <item>Each line, through the shared <see cref="OrderLineMatcher"/> (decision #100) with the complementary rules:
    /// the item is given ("Item is required."), on the parent ("Cheese is not on order #12."; an id that names no item at
    /// all gets "Item {id} is not on order #12.", decision #96), and not repeated ("Cheese appears on more than one
    /// line."); the requested amount is given ("Requested amount is required."), greater than 0, at most 3 decimal places,
    /// and at most 999,999,999.999 (decision #80). Unlike a send, a request names only the materials it needs.</item>
    /// </list>
    /// </remarks>
    /// <returns>The trimmed reason and the valid lines, in body order.</returns>
    private async Task<(string Reason, List<MatchedOrderLine> Lines)> ValidateAsync(
        ProductionOrder parent, ComplementaryOrderRequest request, CancellationToken cancellationToken)
    {
        var errors = new ValidationErrors();

        var reason = Text.Clean(request.Reason);
        if (reason is null)
        {
            errors.Add("reason", "Reason is required.");
        }
        // Decision #116: counted in Unicode code points, so an emoji is one character (Text.Length).
        else if (Text.Length(reason) > ColumnRules.TextLength)
        {
            errors.Add("reason", $"Reason must be {ColumnRules.TextLength} characters or fewer.");
        }

        var submitted = (request.Lines ?? [])
            .Select(line => line is null ? null : new SubmittedOrderLine(line.ItemId, line.RequestedAmount))
            .ToList();

        List<MatchedOrderLine> lines = [];
        if (submitted.Count == 0)
        {
            errors.Add("lines", "At least one line is required.");
        }
        else
        {
            var names = await NamesOfItemsNotOnAsync(parent, submitted, cancellationToken);
            lines = OrderLineMatcher.Match(parent, submitted, "requestedAmount", "Requested amount", errors, new OrderLineRules
            {
                EveryLineRequired = false,
                ZeroAllowed = false,
                NotOnOrderMessage = itemId => names.TryGetValue(itemId, out var name)
                    ? $"{name} is not on order #{parent.Number}."
                    : $"Item {itemId} is not on order #{parent.Number}.",
            });
        }

        errors.ThrowIfAny();

        // ThrowIfAny has thrown if the reason was missing, so it is not null here; "!" tells the compiler so.
        return (reason!, lines);
    }

    /// <summary>
    /// The names of the submitted items that are not on <paramref name="parent"/>, so the "not on order" message can name
    /// the item (design 7.2). One query for all of them; an id that names no item is simply absent.
    /// </summary>
    private async Task<Dictionary<int, string>> NamesOfItemsNotOnAsync(
        ProductionOrder parent, IEnumerable<SubmittedOrderLine?> submitted, CancellationToken cancellationToken)
    {
        var onParent = parent.Lines.Select(line => line.RawMaterialId).ToHashSet();
        var others = submitted
            .Select(line => line?.ItemId)
            .OfType<int>()
            .Where(itemId => !onParent.Contains(itemId))
            .Distinct()
            .ToList();
        if (others.Count == 0)
        {
            return new Dictionary<int, string>();
        }

        // Only read, never changed, so not tracked (like the parent order above).
        return await db.Items
            .AsNoTracking()
            .Where(item => others.Contains(item.Id))
            .ToDictionaryAsync(item => item.Id, item => item.Name, cancellationToken);
    }

    /// <summary>
    /// Design 2.2 step 5, AC-16.2: the parent must be InProduction. Otherwise <c>409</c> <c>parent-not-in-production</c>
    /// "Order #{n} is {status}. Complementary orders can be raised only while the order is in production." (design 7.2).
    /// A Created order has not been sent yet (its own send covers the plan); a Completed or Cancelled one has no run left
    /// to top up.
    /// </summary>
    private static void CheckParentInProduction(ProductionOrder parent)
    {
        if (parent.Status != OrderStatus.InProduction)
        {
            throw new ConflictException(ParentNotInProductionCode,
                $"Order #{parent.Number} is {parent.Status}. Complementary orders can be raised only while the order is in production.");
        }
    }

    /// <summary>
    /// AC-16.1, AC-23.2: adds the ComplementaryAwaitingApproval notification through <see cref="NotificationComposer"/>
    /// (T-005): the complementary order number, each material with its requested amount and unit, the reason, and the
    /// requesting user (design 5.10, 7.3), at the request's time.
    /// </summary>
    /// <remarks>
    /// Each material carries its line number on the <em>parent</em> order, so the composer lists them in recipe line order
    /// (design 7.3), whatever order the client sent them in. The requester's email is read here, inside the transaction,
    /// because the token carries only the user id the service is given.
    /// </remarks>
    private async Task AddNotificationAsync(
        ProductionOrder parent,
        int complementaryNumber,
        IEnumerable<MatchedOrderLine> lines,
        string reason,
        string userId,
        DateTime now,
        CancellationToken cancellationToken)
    {
        var requester = await db.Users.AsNoTracking()
            .Where(user => user.Id == userId)
            .Select(user => new NotificationUser(user.Id, user.Email!))
            .SingleAsync(cancellationToken);

        var materials = lines.Select(line => new NotificationMaterial(
            line.Line.LineNo, line.Line.RawMaterialId, line.Line.RawMaterial.Name, line.Line.RawMaterial.Unit.Name,
            line.Quantity));

        db.Notifications.Add(NotificationComposer.ComplementaryAwaitingApproval(
            parent.Number, complementaryNumber, materials, reason, requester, now));
    }
}
